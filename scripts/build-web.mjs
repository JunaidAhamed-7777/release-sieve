import { createHash } from 'node:crypto';
import { copyFile, mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { build } from 'esbuild';
import { MODEL, MODEL_ROOT, ROOT, verifyModelFiles } from '../src/model.mjs';

const outputRoot = path.join(ROOT, 'docs');
const workerOnly = process.argv.includes('--worker-only');
const assetRoot = path.join(outputRoot, 'assets');
const licenseRoot = path.join(outputRoot, 'licenses');
await mkdir(assetRoot, { recursive: true });
await mkdir(licenseRoot, { recursive: true });
const modelLock = await verifyModelFiles();
const transformersPackage = JSON.parse(await readFile(path.join(ROOT, 'node_modules/@huggingface/transformers/package.json'), 'utf8'));
if (transformersPackage.version !== '4.3.1') throw new Error('The fixed BERT browser adapter requires Transformers.js 4.3.1. Install the exact lockfile dependencies before building.');
const runtimePackage = JSON.parse(await readFile(path.join(ROOT, 'node_modules/onnxruntime-web/package.json'), 'utf8'));
const runtimeFiles = [];
for (const filename of ['ort-wasm-simd-threaded.wasm', 'ort-wasm-simd-threaded.mjs']) {
  const source = path.join(ROOT, 'node_modules/onnxruntime-web/dist', filename);
  const bytes = await readFile(source);
  await copyFile(source, path.join(assetRoot, filename));
  runtimeFiles.push({ path: filename, url: `assets/${filename}`, bytes: bytes.length, sha256: createHash('sha256').update(bytes).digest('hex') });
}
const modelFiles = [];
for (const file of modelLock.files) {
  const relative = `models/${MODEL.revision}/${MODEL.id}/${file.path}`;
  const destination = path.join(outputRoot, relative);
  await mkdir(path.dirname(destination), { recursive: true });
  await copyFile(path.join(MODEL_ROOT, MODEL.id, file.path), destination);
  modelFiles.push({ ...file, url: relative });
}
const manifest = {
  id: MODEL.id, revision: MODEL.revision, license: modelLock.license, dtype: 'q8', dimensions: 384, maxTokens: 256,
  files: modelFiles,
  runtime: { package: '@huggingface/transformers', version: '4.3.1', backend: 'onnxruntime-web/wasm', backendVersion: runtimePackage.version, files: runtimeFiles },
};
await writeFile(path.join(ROOT, 'web/model-manifest.mjs'), `// Generated by scripts/build-web.mjs from verified local assets.\nexport const MODEL_MANIFEST = Object.freeze(${JSON.stringify(manifest, null, 2)});\n`);
const sourceRoot = path.join(ROOT, 'node_modules/@huggingface/transformers/src');
const fixedModelBrowser = {
  name: 'fixed-bert-browser-runtime',
  setup(builder) {
    builder.onResolve({ filter: /^@release-sieve\/transformers\// }, ({ path: specifier }) => {
      const relative = specifier.slice('@release-sieve/transformers/'.length);
      const allowed = new Set([
        'env.js', 'utils/tensor.js', 'models/modeling_utils.js', 'models/session_config.js',
        'models/bert/modeling_bert.js', 'models/bert/tokenization_bert.js',
      ]);
      if (!allowed.has(relative)) throw new Error('Unexpected runtime source import.');
      return { path: path.join(sourceRoot, relative) };
    });
    // Match the upstream browser build's empty Node/image-only modules.
    builder.onResolve({ filter: /^(?:node:.*|sharp)$|^\.\/onnx-node\.js$/ }, ({ path: specifier }) => ({ path: specifier, namespace: 'browser-empty-module' }));
    builder.onLoad({ filter: /.*/, namespace: 'browser-empty-module' }, () => ({ contents: 'export default {};', loader: 'js' }));
  },
};
const bundled = await build({
  absWorkingDir: ROOT,
  entryPoints: workerOnly ? { worker: 'web/worker.mjs' } : { app: 'web/app.mjs', worker: 'web/worker.mjs' },
  outdir: assetRoot, outExtension: { '.js': '.mjs' },
  platform: 'browser', format: 'esm', bundle: true, minify: true, target: ['es2022'],
  conditions: ['browser', 'onnxruntime-web-use-extern-wasm'],
  alias: { 'onnxruntime-web/webgpu': 'onnxruntime-web/wasm' },
  plugins: [fixedModelBrowser],
  legalComments: 'linked', metafile: true, logLevel: 'warning',
  banner: { js: '// Generated browser bundle: application code and dependencies were bundled/minified for Release Sieve. Original licenses and attribution: ../THIRD_PARTY.md and ../licenses/.' },
});
const forbidden = Object.keys(bundled.metafile.inputs).filter((filename) => /node_modules[\\/](?:sharp[\\/]|onnxruntime-node[\\/]|@img[\\/])/.test(filename));
if (forbidden.length) throw new Error(`Browser build unexpectedly included native dependencies: ${forbidden.join(', ')}`);
const unrelatedModels = Object.keys(bundled.metafile.inputs).filter((filename) => /transformers[\\/]src[\\/]models[\\/](?:auto[\\/]|registry\.js|(?:mistral|mixtral)[\\/])/i.test(filename));
if (unrelatedModels.length) throw new Error('Browser build included an unrelated model registry.');
await copyFile(path.join(ROOT, 'web/index.html'), path.join(outputRoot, 'index.html'));
await copyFile(path.join(ROOT, 'web/styles.css'), path.join(outputRoot, 'styles.css'));
await copyFile(path.join(ROOT, 'node_modules/@huggingface/transformers/LICENSE'), path.join(licenseRoot, 'transformers-Apache-2.0.txt'));
await copyFile(path.join(ROOT, 'node_modules/@huggingface/tokenizers/LICENSE'), path.join(licenseRoot, 'tokenizers-Apache-2.0.txt'));
await copyFile(path.join(ROOT, 'node_modules/@huggingface/jinja/LICENSE'), path.join(licenseRoot, 'jinja-MIT.txt'));
// Full ONNX Runtime notices are maintained alongside the copied WASM assets.
for (const required of ['onnxruntime-MIT.txt', 'onnxruntime-ThirdPartyNotices.txt', 'model-README.md']) {
  await readFile(path.join(licenseRoot, required));
}
const builtFiles = [];
async function inventory(directory) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const filename = path.join(directory, entry.name);
    if (entry.isDirectory()) await inventory(filename);
    else {
      const bytes = await readFile(filename);
      builtFiles.push({ path: path.relative(outputRoot, filename).replaceAll(path.sep, '/'), bytes: bytes.length, sha256: createHash('sha256').update(bytes).digest('hex') });
    }
  }
}
await inventory(assetRoot);
for (const file of modelFiles) builtFiles.push({ path: file.url, bytes: file.bytes, sha256: file.sha256 });
for (const filename of ['index.html', 'styles.css']) {
  const bytes = await readFile(path.join(outputRoot, filename));
  builtFiles.push({ path: filename, bytes: bytes.length, sha256: createHash('sha256').update(bytes).digest('hex') });
}
await inventory(licenseRoot);
builtFiles.sort((left, right) => left.path.localeCompare(right.path));
await writeFile(path.join(outputRoot, 'web-assets.json'), JSON.stringify({ schemaVersion: 1, model: { id: MODEL.id, revision: MODEL.revision }, runtime: manifest.runtime, files: builtFiles }, null, 2) + '\n');
const inferenceBytes = [...modelFiles, ...runtimeFiles].reduce((sum, file) => sum + file.bytes, 0);
console.log(JSON.stringify({ assets: builtFiles.length, inferenceBytes, modelBytes: modelFiles.reduce((sum, file) => sum + file.bytes, 0), backend: 'single-thread WASM', nativeDependenciesBundled: false, workerOnly }, null, 2));
